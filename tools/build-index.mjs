#!/usr/bin/env node
// Builds the generated parts of the repo from the chapters themselves:
//
//   README.md                    the stats and the chapter checklist, between the index markers
//   index/by-pattern.md          every solved problem, grouped by pattern
//   index/by-difficulty.md       every solved problem, grouped by difficulty
//   index/by-leetcode-number.md  every solved LeetCode problem, sorted by number
//
// Run it after adding or renaming a chapter or a problem:
//
//   node tools/build-index.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseHeadings } from './lib/markdown.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const INDEX = path.join(ROOT, 'index');
const README = path.join(ROOT, 'README.md');
const PROBLEM = /^P(\d+)\. (.+) \((?:\[LeetCode (\d+)\]\((https:[^)]+)\)|Classic), (Easy|Medium|Hard|Advanced)(, Premium)?\)$/;
const DIFFICULTIES = ['Easy', 'Medium', 'Hard', 'Advanced'];
const GENERATED_NOTE = '> Generated by `node tools/build-index.mjs`. Do not edit this file by hand.';

function readChapter(chapter) {
  const file = path.join(ROOT, chapter.path);
  if (!fs.existsSync(file)) return { ...chapter, written: false, problems: [] };
  const text = fs.readFileSync(file, 'utf8');
  const lines = text.split(/\r?\n/);
  const problems = [];
  for (const heading of parseHeadings(text)) {
    const m = heading.level === 3 && heading.text.match(PROBLEM);
    if (!m) continue;
    const [, , title, lc, url, difficulty, premium] = m;
    const patternLine = lines.slice(heading.line).find((line) => line.startsWith('**Pattern:**')) ?? '';
    const patterns = patternLine.replace('**Pattern:**', '').split(/\s*[,+]\s*/).map((p) => p.trim()).filter(Boolean);
    problems.push({ title, lc: lc ? Number(lc) : null, url, difficulty, premium: Boolean(premium), patterns, chapter, anchor: heading.anchor });
  }
  const cppBlocks = (text.match(/^ {0,3}```cpp\s*$/gm) ?? []).length;
  return { ...chapter, written: true, problems, cppBlocks };
}

function byDifficulty(a, b) {
  return DIFFICULTIES.indexOf(a.difficulty) - DIFFICULTIES.indexOf(b.difficulty) || (a.lc ?? 1e9) - (b.lc ?? 1e9) || a.title.localeCompare(b.title);
}

function source(problem) {
  const premium = problem.premium ? ' (Premium)' : '';
  return problem.lc ? `[LeetCode ${problem.lc}](${problem.url})${premium}` : 'Classic';
}

function problemLink(problem, base) {
  return `[${problem.title}](${base}${problem.chapter.path}#${problem.anchor})`;
}

function table(problems) {
  const rows = problems.map((p) => `| ${problemLink(p, '../')} | ${source(p)} | ${p.difficulty} | ${p.chapter.title} |`);
  return ['| Problem | Source | Difficulty | Chapter |', '|---|---|---|---|', ...rows].join('\n');
}

function writeIndexFile(name, title, intro, body) {
  fs.mkdirSync(INDEX, { recursive: true });
  fs.writeFileSync(path.join(INDEX, name), `# ${title}\n\n${GENERATED_NOTE}\n\n${intro}\n\n${body}\n`);
}

function buildPatternIndex(problems, patterns) {
  const groups = patterns
    .map((pattern) => ({ pattern, items: problems.filter((p) => p.patterns.includes(pattern)).sort(byDifficulty) }))
    .filter((g) => g.items.length);
  const contents = groups.map((g) => `- [${g.pattern}](#${anchorOf(g.pattern)}) (${g.items.length})`).join('\n');
  const body = groups.map((g) => `## ${g.pattern}\n\n${table(g.items)}`).join('\n\n');
  writeIndexFile('by-pattern.md', 'Problems by Pattern', `Practice one pattern at a time. Problems run from easiest to hardest.\n\n${contents}`, body);
}

function anchorOf(text) {
  return parseHeadings(`## ${text}`)[0].anchor;
}

function buildDifficultyIndex(problems) {
  const body = DIFFICULTIES
    .map((d) => [d, problems.filter((p) => p.difficulty === d).sort(byDifficulty)])
    .filter(([, items]) => items.length)
    .map(([d, items]) => `## ${d} (${items.length})\n\n${table(items)}`)
    .join('\n\n');
  writeIndexFile('by-difficulty.md', 'Problems by Difficulty', 'Every solved problem, grouped by difficulty.', body);
}

function buildNumberIndex(problems) {
  const numbered = problems.filter((p) => p.lc).sort((a, b) => a.lc - b.lc);
  const seen = new Set();
  const rows = numbered.filter((p) => !seen.has(p.lc) && seen.add(p.lc)).map((p) => {
    return `| ${p.lc} | ${problemLink(p, '../')} | ${p.difficulty}${p.premium ? ' (Premium)' : ''} | ${p.patterns.join(', ')} |`;
  });
  const body = ['| # | Problem | Difficulty | Pattern |', '|---|---|---|---|', ...rows].join('\n');
  writeIndexFile('by-leetcode-number.md', 'Problems by LeetCode Number', 'Use this to check whether a LeetCode problem is solved in this guide.', body);
}

function buildReadme(parts, stats) {
  const checklist = parts.map((part) => {
    const items = part.chapters.map((c) => {
      const count = c.problems.length ? ` · ${c.problems.length} problems` : '';
      return c.written ? `- [ ] [${c.title}](${c.path}) \`${c.tier}\`${count}` : `- [ ] ${c.title} \`${c.tier}\` (not written yet)`;
    });
    return `### ${part.title}\n\n${part.summary}\n\n${items.join('\n')}`;
  }).join('\n\n');
  const section = (name, content) => [`<!-- ${name}:start -->`, content, `<!-- ${name}:end -->`].join('\n');
  const replaceSection = (text, name, content) => {
    const pattern = new RegExp(`<!-- ${name}:start -->[\\s\\S]*<!-- ${name}:end -->`);
    if (!pattern.test(text)) throw new Error(`README.md has no ${name} markers`);
    return text.replace(pattern, () => section(name, content));
  };
  const summary = `**${stats.chapters} chapters · ${stats.problems} solved problems (${stats.leetcode} from LeetCode, ${stats.classic} classics) · ${stats.programs} tested C++ programs**`;
  let text = fs.readFileSync(README, 'utf8');
  text = replaceSection(text, 'stats', summary);
  text = replaceSection(text, 'index', checklist);
  fs.writeFileSync(README, text);
}

const curriculum = JSON.parse(fs.readFileSync(path.join(ROOT, 'tools', 'data', 'curriculum.json'), 'utf8'));
const parts = curriculum.parts.map((part) => ({ ...part, chapters: part.chapters.map(readChapter) }));
const chapters = parts.flatMap((part) => part.chapters);
const problems = chapters.flatMap((c) => c.problems);

buildPatternIndex(problems, curriculum.patterns);
buildDifficultyIndex(problems);
buildNumberIndex(problems);

const stats = {
  chapters: chapters.filter((c) => c.written).length,
  problems: problems.length,
  leetcode: new Set(problems.filter((p) => p.lc).map((p) => p.lc)).size,
  classic: problems.filter((p) => !p.lc).length,
  programs: chapters.reduce((total, c) => total + (c.cppBlocks ?? 0), 0),
};
if (fs.existsSync(README)) buildReadme(parts, stats);
console.log(`${stats.chapters} of ${chapters.length} chapters written, ${stats.problems} problems, ${stats.programs} programs`);
