#!/usr/bin/env node
// Checks the notes: lints every Markdown file, then compiles and runs every C++ block.
//
//   node tools/verify.mjs                     check the whole repo
//   node tools/verify.mjs 05-core-patterns    check one folder
//   node tools/verify.mjs path/to/file.md     check one file
//   node tools/verify.mjs --lint-only         skip compiling
//   node tools/verify.mjs --jobs 4            limit parallel compiles
//   node tools/verify.mjs --export            also write every runnable block to code/
//   node tools/verify.mjs --allow-planned     links to chapters in the curriculum that are not
//                                             written yet are not errors
//
// How a fenced block is treated depends on its info string:
//
//   ```cpp            full program with main(). Compiled and run, must exit with 0.
//   ```cpp compile    no main() needed. Compiled only (syntax and types are checked).
//   ```cpp snippet    short fragment. Not compiled, 25 lines at most.
//   ```text output    expected stdout of the cpp block right above it.
//
// Passed blocks are remembered in build/passed, so a second run only rebuilds what changed.

import { spawn, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadCurriculum, sizeBudgetKB } from './lib/curriculum.mjs';
import { loadProblems, slugOf } from './lib/leetcode.mjs';
import { githubAnchor, parseHeadings, stripCode } from './lib/markdown.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BUILD = path.join(ROOT, 'build');
const PASSED = path.join(BUILD, 'passed');
const TMP = path.join(BUILD, 'tmp');
const CODE = path.join(ROOT, 'code');

// _GLIBCXX_ASSERTIONS catches out-of-bounds vector access. The sanitizer traps on signed overflow
// and other undefined behaviour. -static means the exe runs without the compiler's DLLs on PATH.
const CXXFLAGS = [
  '-std=c++17', '-O1', '-Wall', '-Wextra', '-Werror', '-D_GLIBCXX_ASSERTIONS',
  '-fsanitize=undefined', '-fsanitize-undefined-trap-on-error', '-pthread', '-static',
];
const RUN_TIMEOUT_MS = 20000;
const SNIPPET_MAX_LINES = 25;
const PRELUDE = '#include <bits/stdc++.h>\nusing namespace std;\n';
const SKIP_DIRS = new Set(['node_modules', 'build', 'code', '.git', '.claude', 'tools']);
const BANNED_WORDS = /\b(claude|anthropic|chatgpt|gpt-\d|as an ai|ai assistant|ai-generated|generated by ai)\b/i;
const LEFTOVER_MARKERS = /<!--\s*CONTINUE\s*-->|\bTODO\b|\bTBD\b|\bFIXME\b/;
const PROBLEM_HEADING = /^### P(\d+)\. (.+) \((?:\[LeetCode (\d+)\]\(https:\/\/leetcode\.com\/problems\/([a-z0-9-]+)\/\)|Classic), (Easy|Medium|Hard|Advanced)(, Premium)?\)$/;
const PROBLEM_FIELDS = ['**Problem:**', '**Example:**', '**Pattern:**', '**How to recognize it:**', '**Key idea:**', '**Complexity:**'];
const CHAPTER_PARTS = /^(0[2-9]|1[0-3])-/;
const CHAPTER_SECTIONS = ['Quick revision', 'How to recognize', 'Common pitfalls', 'Interview questions'];

function parseArgs(argv) {
  const opts = { targets: [], jobs: Math.max(2, Math.floor(os.cpus().length / 3)), lintOnly: false, exportCode: false, allowPlanned: false };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--jobs') opts.jobs = Number(argv[++i]);
    else if (argv[i] === '--lint-only') opts.lintOnly = true;
    else if (argv[i] === '--export') opts.exportCode = true;
    else if (argv[i] === '--allow-planned') opts.allowPlanned = true;
    else opts.targets.push(argv[i]);
  }
  return opts;
}

function findCompiler() {
  if (process.env.CXX) return process.env.CXX;
  if (!spawnSync('g++', ['--version']).error) return 'g++';
  // A shell opened before the winget install does not have g++ on PATH yet.
  const packages = path.join(process.env.LOCALAPPDATA ?? '', 'Microsoft', 'WinGet', 'Packages');
  if (fs.existsSync(packages)) {
    for (const dir of fs.readdirSync(packages)) {
      const candidate = path.join(packages, dir, 'mingw64', 'bin', 'g++.exe');
      if (dir.startsWith('BrechtSanders.WinLibs') && fs.existsSync(candidate)) return candidate;
    }
  }
  throw new Error('g++ not found. Install it with: winget install BrechtSanders.WinLibs.POSIX.UCRT');
}

function collectMarkdown(target, found = []) {
  const stat = fs.statSync(target);
  if (stat.isFile()) {
    if (target.endsWith('.md')) found.push(target);
    return found;
  }
  for (const entry of fs.readdirSync(target, { withFileTypes: true })) {
    if (entry.isDirectory() && SKIP_DIRS.has(entry.name)) continue;
    collectMarkdown(path.join(target, entry.name), found);
  }
  return found;
}

function parseBlocks(lines) {
  const blocks = [];
  let open = null;
  lines.forEach((line, index) => {
    if (!open) {
      const m = line.match(/^ {0,3}(`{3,})\s*([^\s`]*)\s*(.*?)\s*$/);
      if (m) open = { fence: m[1].length, lang: m[2], tag: m[3], start: index + 1, body: [] };
      return;
    }
    if (new RegExp(`^ {0,3}\`{${open.fence},}\\s*$`).test(line)) {
      blocks.push({ ...open, end: index + 1, code: open.body.join('\n') + '\n' });
      open = null;
    } else {
      open.body.push(line);
    }
  });
  if (open) blocks.push({ ...open, end: lines.length, code: '', unclosed: true });
  return blocks;
}

function lintFile(rel, text, lines, blocks, problemsByNumber, problemsBySlug, planned, curriculum) {
  const issues = [];
  const add = (line, msg) => issues.push({ line, msg });
  const inCode = new Set();
  for (const b of blocks) for (let i = b.start; i <= b.end; i++) inCode.add(i);

  lines.forEach((line, index) => {
    const n = index + 1;
    if (/[—–]/.test(line)) add(n, 'em or en dash: use a comma, colon, parentheses, period or plain hyphen');
    if (BANNED_WORDS.test(line)) add(n, `banned word: ${line.match(BANNED_WORDS)[0]}`);
    if (LEFTOVER_MARKERS.test(line)) add(n, `leftover marker: ${line.match(LEFTOVER_MARKERS)[0]}`);
  });

  for (const b of blocks) {
    if (b.unclosed) add(b.start, 'code fence is never closed');
    if (b.lang === 'cpp' && !['', 'compile', 'snippet'].includes(b.tag)) add(b.start, `unknown cpp tag "${b.tag}"`);
    if (b.lang === 'cpp' && b.tag === '') {
      if (!/\bint\s+main\s*\(/.test(b.code)) add(b.start, 'cpp block has no main(): add one with asserts, or tag it "cpp compile" or "cpp snippet"');
      else if (!b.code.includes('assert(') && !b.expected) add(b.start, 'cpp block has no assert() and no "text output" block after it, so nothing checks it');
    }
    if (b.lang === 'cpp' && b.tag === 'snippet' && b.body.length > SNIPPET_MAX_LINES) add(b.start, `snippet is ${b.body.length} lines, the limit is ${SNIPPET_MAX_LINES}: make it a full program`);
    if (b.lang === 'cpp' && /[^\x00-\x7F]/.test(b.code)) add(b.start, 'non-ASCII character in C++ code (Windows consoles garble it)');
    if (b.lang === 'mermaid' && /\[[^"\]][^\]]*[()][^\]]*\]/.test(b.code)) add(b.start, 'mermaid label with parentheses must be quoted, like A["f(x)"]');
    if (b.lang === '') add(b.start, 'fence has no language: use cpp, text, mermaid and so on');
  }

  // Links, with code blocks and inline code removed so examples are not treated as links.
  const anchorsOf = (file) => new Set(parseHeadings(fs.readFileSync(file, 'utf8')).map((h) => h.anchor));
  stripCode(lines, inCode).forEach((line, index) => {
    for (const m of line.matchAll(/\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) {
      const url = m[1];
      if (/^https:\/\/leetcode\.com\/problems\//.test(url)) {
        const slug = url.match(/problems\/([a-z0-9-]+)\/$/)?.[1];
        if (!slug) add(index + 1, `LeetCode link must look like https://leetcode.com/problems/slug/ : ${url}`);
        else if (!problemsBySlug.has(slug)) add(index + 1, `unknown LeetCode problem: ${slug}`);
        continue;
      }
      if (/^[a-z]+:/i.test(url)) continue;
      const [filePart, anchor] = url.split('#');
      const targetFile = filePart ? path.resolve(path.dirname(path.join(ROOT, rel)), decodeURI(filePart)) : path.join(ROOT, rel);
      if (!fs.existsSync(targetFile)) {
        if (!planned.has(targetFile)) add(index + 1, `broken link: ${url}`);
        continue;
      }
      if (anchor && targetFile.endsWith('.md') && !anchorsOf(targetFile).has(anchor)) add(index + 1, `broken anchor: ${url}`);
    }
  });

  // Problem headings must be exact, because the index is generated from them.
  const seen = new Set();
  lines.forEach((line, index) => {
    if (!/^### P\d/.test(line)) return;
    const m = line.match(PROBLEM_HEADING);
    if (!m) { add(index + 1, `bad problem heading, expected "### P1. Title ([LeetCode 1](url), Easy)" or "### P1. Title (Classic, Easy)": ${line}`); return; }
    const [, num, title, lc, slug, difficulty, premium] = m;
    if (seen.has(num)) add(index + 1, `duplicate problem number P${num}`);
    seen.add(num);
    if (lc) {
      const p = problemsByNumber.get(Number(lc));
      if (!p) { add(index + 1, `no LeetCode problem numbered ${lc}`); return; }
      if (p.title !== title) add(index + 1, `LeetCode ${lc} is titled "${p.title}", not "${title}"`);
      if (p.difficulty !== difficulty) add(index + 1, `LeetCode ${lc} is ${p.difficulty}, not ${difficulty}`);
      if (slugOf(p.title) !== slug) add(index + 1, `LeetCode ${lc} link should end in /${slugOf(p.title)}/`);
      if (p.premium && !premium) add(index + 1, `LeetCode ${lc} is Premium: end the heading with ", ${difficulty}, Premium)"`);
      if (!p.premium && premium) add(index + 1, `LeetCode ${lc} is not Premium: remove ", Premium"`);
    } else if (premium) {
      add(index + 1, 'only LeetCode problems can be marked Premium');
    }
    let endIndex = lines.length;
    for (let i = index + 1; i < lines.length; i++) {
      if (!inCode.has(i + 1) && /^#{1,3} /.test(lines[i])) { endIndex = i; break; }
    }
    const section = lines.slice(index, endIndex).join('\n');
    for (const field of PROBLEM_FIELDS) if (!section.includes(field)) add(index + 1, `P${num} is missing ${field}`);
    const patternLine = section.match(/\*\*Pattern:\*\* *(.+)/)?.[1] ?? '';
    for (const name of patternLine.split(/\s*[,+]\s*/).filter(Boolean)) {
      if (!curriculum.patterns.has(name.trim())) add(index + 1, `P${num} pattern "${name.trim()}" is not in the patterns list of tools/data/curriculum.json`);
    }
    if (!blocks.some((b) => b.lang === 'cpp' && b.tag !== 'snippet' && b.start > index && b.start <= endIndex)) add(index + 1, `P${num} has no compiled C++ block`);
  });

  const chapter = curriculum.byPath.get(rel);
  const budget = chapter && sizeBudgetKB(chapter);
  if (budget && text.length / 1024 > budget && !text.includes('<!-- lint: no-size-limit -->')) {
    add(1, `chapter is ${Math.round(text.length / 1024)} KB, its budget is ${budget} KB: shorten it`);
  }

  const folder = rel.split(/[\\/]/)[0];
  if (CHAPTER_PARTS.test(folder) && /^\d{2}-/.test(path.basename(rel)) && !text.includes('<!-- lint: no-structure -->')) {
    const headings = parseHeadings(text).filter((h) => h.level === 2).map((h) => h.text.toLowerCase());
    for (const section of CHAPTER_SECTIONS) {
      if (!headings.some((h) => h.includes(section.toLowerCase()))) add(1, `chapter has no "## ${section}" section`);
    }
    if (!/^> \*\*Level:\*\*/m.test(text)) add(1, 'chapter has no "> **Level:**" line');
  }
  return issues;
}

function run(command, args, options, timeoutMs) {
  return new Promise((resolve) => {
    const child = spawn(command, args, options);
    let stdout = '';
    let stderr = '';
    let timedOut = false;
    const timer = timeoutMs ? setTimeout(() => { timedOut = true; child.kill(); }, timeoutMs) : null;
    child.stdout?.on('data', (d) => { if (stdout.length < 1 << 20) stdout += d; });
    child.stderr?.on('data', (d) => { if (stderr.length < 1 << 20) stderr += d; });
    child.on('error', (error) => { if (timer) clearTimeout(timer); resolve({ code: -1, stdout, stderr: String(error), timedOut }); });
    child.on('close', (code) => { if (timer) clearTimeout(timer); resolve({ code, stdout, stderr, timedOut }); });
  });
}

// Compiler and assert messages name main.cpp, so translate those lines back to the Markdown file.
function toMarkdownLines(message, rel, block, offset) {
  return message
    .replace(/(?:[\w:./\\-]*[\\/])?main\.cpp:(\d+)/g, (_, n) => `${rel}:${block.start + Number(n) - offset}`)
    .replace(/file main\.cpp, line (\d+)/g, (_, n) => `file ${rel}, line ${block.start + Number(n) - offset}`);
}

function shortError(message, maxLines = 14) {
  const lines = message.split(/\r?\n/).filter(Boolean);
  const important = lines.filter((l) => /error|Assertion|Error/.test(l));
  return (important.length ? important : lines).slice(0, maxLines).join('\n    ');
}

async function checkBlock(block, rel, compiler) {
  const compileOnly = block.tag === 'compile';
  const needsPrelude = compileOnly && !block.code.includes('#include');
  const source = (needsPrelude ? PRELUDE : '') + block.code;
  const offset = needsPrelude ? 2 : 0;
  const key = createHash('sha1').update(CXXFLAGS.join(' ')).update('\0').update(source).update('\0').update(block.expected ?? '').update(block.tag).digest('hex');
  const marker = path.join(PASSED, key);
  if (fs.existsSync(marker)) return { cached: true };

  const dir = path.join(TMP, `${key}-${process.pid}`);
  fs.mkdirSync(dir, { recursive: true });
  try {
    fs.writeFileSync(path.join(dir, 'main.cpp'), source);
    const args = compileOnly ? [...CXXFLAGS.filter((f) => f !== '-static'), '-fsyntax-only', 'main.cpp'] : [...CXXFLAGS, 'main.cpp', '-o', 'main.exe'];
    const compiled = await run(compiler, args, { cwd: dir, stdio: ['ignore', 'pipe', 'pipe'] });
    if (compiled.code !== 0) return { error: `compile error\n    ${toMarkdownLines(shortError(compiled.stderr), rel, block, offset)}` };
    if (!compileOnly) {
      const result = await run(path.join(dir, 'main.exe'), [], { cwd: dir, stdio: ['ignore', 'pipe', 'pipe'] }, RUN_TIMEOUT_MS);
      if (result.timedOut) return { error: `timed out after ${RUN_TIMEOUT_MS / 1000}s: infinite loop, or too slow` };
      if (result.code !== 0) {
        const hex = result.code > 255 ? ` (0x${(result.code >>> 0).toString(16)})` : '';
        const detail = toMarkdownLines(shortError(result.stderr), rel, block, offset);
        return { error: `exited with code ${result.code}${hex}\n    ${detail || explainExit(result.code)}` };
      }
      if (block.expected !== undefined) {
        const clean = (s) => s.replace(/\r/g, '').split('\n').map((l) => l.trimEnd()).join('\n').trimEnd();
        if (clean(result.stdout) !== clean(block.expected)) {
          return { error: `stdout does not match the "text output" block at line ${block.outputLine}\n    expected: ${JSON.stringify(clean(block.expected)).slice(0, 400)}\n    actual:   ${JSON.stringify(clean(result.stdout)).slice(0, 400)}` };
        }
      }
    }
    fs.writeFileSync(marker, '');
    return { passed: true };
  } finally {
    fs.rmSync(dir, { recursive: true, force: true, maxRetries: 3, retryDelay: 200 });
  }
}

function explainExit(code) {
  const unsigned = code >>> 0;
  if (unsigned === 0xc0000005) return 'segmentation fault: invalid memory access';
  if (unsigned === 0xc00000fd) return 'stack overflow: recursion too deep';
  if (unsigned === 0xc000001d) return 'undefined behaviour trap: usually signed integer overflow';
  if (unsigned === 0xc0000094) return 'integer division by zero';
  return 'no message on stderr';
}

async function pool(items, limit, work) {
  let next = 0;
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (next < items.length) {
      const index = next++;
      await work(items[index], index);
    }
  }));
}

function exportBlocks(rel, lines, blocks) {
  const headings = parseHeadings(lines.join('\n'));
  const folder = path.join(CODE, rel.replace(/\.md$/, ''));
  const runnable = blocks.filter((b) => b.lang === 'cpp' && b.tag === '');
  if (!runnable.length) return 0;
  fs.rmSync(folder, { recursive: true, force: true });
  fs.mkdirSync(folder, { recursive: true });
  runnable.forEach((b, i) => {
    const heading = headings.filter((h) => h.line < b.start).at(-1);
    const name = githubAnchor(heading?.text ?? 'block').slice(0, 60).replace(/-+$/, '');
    fs.writeFileSync(path.join(folder, `${String(i + 1).padStart(2, '0')}-${name}.cpp`), `// From ${rel.replaceAll('\\', '/')}, line ${b.start}\n${b.code}`);
  });
  return runnable.length;
}

async function main() {
  const opts = parseArgs(process.argv.slice(2));
  const targets = opts.targets.length ? opts.targets.map((t) => path.resolve(t)) : [ROOT];
  const files = [...new Set(targets.flatMap((t) => collectMarkdown(t)))].sort();
  const { byNumber, bySlug } = loadProblems();
  const curriculum = loadCurriculum();
  const planned = opts.allowPlanned ? new Set(curriculum.chapters.map((c) => path.resolve(ROOT, c.path))) : new Set();
  const allIssues = [];
  const work = [];
  let exported = 0;

  for (const file of files) {
    const rel = path.relative(ROOT, file).replaceAll('\\', '/');
    const text = fs.readFileSync(file, 'utf8');
    const lines = text.split(/\r?\n/);
    const blocks = parseBlocks(lines);
    blocks.forEach((b, i) => {
      const next = blocks[i + 1];
      if (b.lang === 'cpp' && b.tag === '' && next?.lang === 'text' && next.tag === 'output') {
        b.expected = next.code;
        b.outputLine = next.start;
      }
    });
    for (const issue of lintFile(rel, text, lines, blocks, byNumber, bySlug, planned, curriculum)) allIssues.push({ rel, ...issue });
    for (const b of blocks) {
      const isProgram = b.tag === 'compile' || /\bint\s+main\s*\(/.test(b.code);
      if (b.lang === 'cpp' && b.tag !== 'snippet' && isProgram) work.push({ rel, block: b });
    }
    if (opts.exportCode) exported += exportBlocks(rel, lines, blocks);
  }

  let passed = 0;
  let cached = 0;
  const failures = [];
  if (!opts.lintOnly && work.length) {
    const compiler = findCompiler();
    fs.mkdirSync(PASSED, { recursive: true });
    fs.mkdirSync(TMP, { recursive: true });
    await pool(work, opts.jobs, async ({ rel, block }) => {
      const result = await checkBlock(block, rel, compiler);
      if (result.cached) cached++;
      else if (result.passed) passed++;
      else failures.push({ rel, line: block.start, error: result.error });
    });
  }

  allIssues.sort((a, b) => a.rel.localeCompare(b.rel) || a.line - b.line);
  failures.sort((a, b) => a.rel.localeCompare(b.rel) || a.line - b.line);
  for (const i of allIssues) console.log(`LINT ${i.rel}:${i.line}: ${i.msg}`);
  for (const f of failures) console.log(`FAIL ${f.rel}:${f.line}: ${f.error}`);
  const compiled = opts.lintOnly ? 'compile skipped' : `${work.length} code blocks: ${passed} newly passed, ${cached} already passed, ${failures.length} failed`;
  console.log(`\n${files.length} files, ${compiled}, ${allIssues.length} lint errors${opts.exportCode ? `, ${exported} programs exported to code/` : ''}`);
  process.exit(allIssues.length || failures.length ? 1 : 0);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(2);
});
